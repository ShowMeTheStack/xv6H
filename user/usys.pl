#!/usr/bin/perl -w

# Generate usys.S, the stubs for syscalls.

print "# generated by usys.pl - do not edit\n";

print "#include \"kernel/syscall.h\"\n";

# entry(NAME [, SYSCALL]) emits the stub NAME for the system call of
# the same name, or for SYSCALL when the two differ: exit() belongs to
# the library, which flushes the streams before calling _exit(), and
# sbrk() takes a flag the standard form does not have.
sub entry {
    my $name = shift;
    my $call = shift // $name;
    if ($name eq "sbrk") {
	print ".global sys_$name\n";
	print "sys_$name:\n";
    } else {
	print ".global $name\n";
	print "$name:\n";
    }
    print " li a7, SYS_${call}\n";
    print " ecall\n";
    # the kernel returns -errno; report it the way C expects
    print " bltz a0, __syscall_ret\n";
    print " ret\n";
}
	
