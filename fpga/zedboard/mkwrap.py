#!/usr/bin/env python3
# Generate rocket_wrap.v around the generated ExampleRocketSystem (port list read from the
# generated .sv, nothing typed by hand). The wrapper:
#   - renames the AXI4 master ports to Vivado's interface naming (m_mem_axi_*, m_mmio_axi_*), so
#     the block design infers two AXI4 masters;
#   - remaps the memory port: Rocket's RAM at 0x8000_0000..0x8fff_ffff becomes the ZedBoard's
#     DDR 0x1000_0000..0x1fff_ffff behind the PS's S_AXI_HP0 (the PS keeps the lower 256 MB);
#   - drives every clock from one clock and every reset from one reset;
#   - ties off the debug module's DMI and the L2 front-bus slave (unused);
#   - brings out the four external interrupts.
#   mkwrap.py ExampleRocketSystem.sv > rocket_wrap.v
import re, sys
src = open(sys.argv[1]).read()
m = re.search(r"module ExampleRocketSystem\((.*?)\);", src, re.S)
ports = []
direction, width = None, ""
for line in m.group(1).splitlines():
    line = line.split("//")[0].strip().rstrip(",")
    if not line:
        continue
    mm = re.match(r"(input|output)\s+(\[[^\]]+\])?\s*(\w+)", line)
    if mm:
        direction, width, name = mm.group(1), mm.group(2) or "", mm.group(3)
    else:
        name = line.strip()
    ports.append((direction, width, name))

def axi_name(prefix, name, newp):
    # mem_axi4_0_aw_bits_addr -> m_mem_axi_awaddr ; mem_axi4_0_aw_valid -> m_mem_axi_awvalid
    rest = name[len(prefix):]
    mm = re.match(r"(aw|w|b|ar|r)_(?:bits_)?(\w+)", rest)
    ch, sig = mm.group(1), mm.group(2)
    return "%s_%s%s" % (newp, ch, sig)

out = ["// generated by fpga/zedboard/mkwrap.py from ExampleRocketSystem.sv -- do not edit",
       "module rocket_wrap (",
       "  (* X_INTERFACE_INFO = \"xilinx.com:signal:clock:1.0 clk CLK\" *)",
       "  (* X_INTERFACE_PARAMETER = \"ASSOCIATED_BUSIF m_mem_axi:m_mmio_axi, ASSOCIATED_RESET resetn\" *)",
       "  input  wire clk,",
       "  (* X_INTERFACE_INFO = \"xilinx.com:signal:reset:1.0 resetn RST\" *)",
       "  (* X_INTERFACE_PARAMETER = \"POLARITY ACTIVE_LOW\" *)",
       "  input  wire resetn,",
       "  input  wire [3:0] irq,"]
decl, conn = [], []
for d, w, n in ports:
    if n.startswith("mem_axi4_0_"):
        nn = axi_name("mem_axi4_0_", n, "m_mem_axi")
        if n in ("mem_axi4_0_aw_bits_addr", "mem_axi4_0_ar_bits_addr", "mem_axi4_0_aw_bits_prot", "mem_axi4_0_ar_bits_prot"):
            decl.append("  %s wire %s %s," % (d, w, nn))
            conn.append("    .%s(%s_raw)," % (n, nn))
        else:
            decl.append("  %s wire %s %s," % (d, w, nn)); conn.append("    .%s(%s)," % (n, nn))
    elif n.startswith("mmio_axi4_0_"):
        nn = axi_name("mmio_axi4_0_", n, "m_mmio_axi")
        decl.append("  %s wire %s %s," % (d, w, nn)); conn.append("    .%s(%s)," % (n, nn))
    # whole names only: a prefix match takes debug_clock for debug_clockeddmi_dmi_req_ready and
    # the other DMI ports, ties Rocket's clock to its own outputs, and Vivado resolves the
    # multi-driven net to a constant, sweeping the whole core away in implementation
    elif re.fullmatch(r"io_aggregator_\d+_clock|debug_clock|debug_clockeddmi_dmiClock", n):
        conn.append("    .%s(clk)," % n)
    elif re.fullmatch(r"io_aggregator_\d+_reset|debug_reset|debug_clockeddmi_dmiReset|resetctrl_hartIsInReset_\d+", n):
        conn.append("    .%s(~resetn)," % n)
    elif n == "interrupts":
        conn.append("    .interrupts(irq),")
    elif n.startswith("l2_frontend_bus_axi4_0_"):
        if d == "input":
            conn.append("    .%s(%s)," % (n, "0"))
        else:
            conn.append("    .%s()," % n)
    elif n.startswith("debug_"):
        if d == "input":
            conn.append("    .%s(%s)," % (n, "0"))
        else:
            conn.append("    .%s()," % n)
    else:
        raise SystemExit("unhandled port: %s %s %s" % (d, w, n))
decl[-1] = decl[-1].rstrip(",")
out += decl + [");",
  "  wire [31:0] m_mem_axi_awaddr_raw, m_mem_axi_araddr_raw;",
  "  // 0x8xxx_xxxx -> 0x1xxx_xxxx: the upper 256 MB of the ZedBoard's DDR",
  "  assign m_mem_axi_awaddr = {4'h1, m_mem_axi_awaddr_raw[27:0]};",
  "  assign m_mem_axi_araddr = {4'h1, m_mem_axi_araddr_raw[27:0]};",
  "  // secure, as the PS's own masters are: Rocket marks its accesses non-secure (AxPROT[1]),",
  "  // and DDR the TrustZone controller has not been told about is secure after reset",
  "  wire [2:0] m_mem_axi_awprot_raw, m_mem_axi_arprot_raw;",
  "  assign m_mem_axi_awprot = 3'b000;",
  "  assign m_mem_axi_arprot = 3'b000;",
  "  ExampleRocketSystem rocket ("]
conn[-1] = conn[-1].rstrip(",")
out += conn + ["  );", "endmodule"]
print("\n".join(out))
